// Language Switcher Logic
const langSwitcher = document.getElementById('lang-switcher');

langSwitcher.addEventListener('change', (e) => {
    const selectedLang = e.target.value;
    updateLanguage(selectedLang);
});

function updateLanguage(lang) {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });
    
    // Also update document title specifically if it has data-i18n (it does, but textContent doesn't always work perfectly for <title> in some older browsers, though it should be fine here)
    const titleKey = document.title = translations[lang]['pageTitle'];
}


// Navbar Scroll Effect
window.addEventListener('scroll', () => {
    const navbar = document.querySelector('.navbar');
    if (window.scrollY > 50) {
        navbar.classList.add('scrolled');
    } else {
        navbar.classList.remove('scrolled');
    }
});

// Mobile Menu Toggle
const hamburger = document.querySelector('.hamburger');
const navLinks = document.querySelector('.nav-links');

hamburger.addEventListener('click', () => {
    navLinks.classList.toggle('active');
    // Optional: animate hamburger into an X
});

// Close mobile menu when a link is clicked
document.querySelectorAll('.nav-links a').forEach(link => {
    link.addEventListener('click', () => {
        navLinks.classList.remove('active');
    });
});

// Donation Method Toggle
const btnQr = document.getElementById('btn-qr');
const btnBank = document.getElementById('btn-bank');
const qrView = document.getElementById('qr-view');
const bankView = document.getElementById('bank-view');
const donationInstructionText = document.getElementById('donation-instruction-text');

btnQr.addEventListener('click', () => {
    btnQr.classList.add('active');
    btnBank.classList.remove('active');
    qrView.style.display = 'block';
    bankView.style.display = 'none';
});

btnBank.addEventListener('click', () => {
    btnBank.classList.add('active');
    btnQr.classList.remove('active');
    qrView.style.display = 'none';
    bankView.style.display = 'block';
});

// Modal Logic
const modal = document.getElementById('qr-modal');
const viewQrBtn = document.getElementById('view-qr-btn');
const closeModal = document.querySelector('.close-modal');

if (viewQrBtn) {
    viewQrBtn.addEventListener('click', () => {
        modal.style.display = 'block';
    });
}

if (closeModal) {
    closeModal.addEventListener('click', () => {
        modal.style.display = 'none';
    });
}

window.addEventListener('click', (e) => {
    if (e.target === modal) {
        modal.style.display = 'none';
    }
});
